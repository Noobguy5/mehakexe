// One-time generator: run `node make-manifest.js` to regenerate media.js
const fs = require("fs");
const path = require("path");

const dir = path.join(__dirname, "phtotos");
const exts = new Set([".jpg", ".jpeg", ".png", ".webp", ".gif", ".bmp"]);
const vids = new Set([".mp4", ".mov", ".webm", ".m4v", ".avi", ".mkv"]);

const files = fs.readdirSync(dir).filter((f) => {
  const ext = path.extname(f).toLowerCase();
  return exts.has(ext) || vids.has(ext);
});

const parse = (name) => {
  // IMG_YYYYMMDD_HHMMSS or VID_YYYYMMDD_...
  let m = name.match(/(?:IMG|VID)_(\d{4})(\d{2})(\d{2})[_-](\d{2})(\d{2})(\d{2})/);
  if (m)
    return {
      date: `${m[1]}-${m[2]}-${m[3]}`,
      time: `${m[4]}:${m[5]}:${m[6]}`,
    };
  // video_YYYYMMDD_HHMMSS or similar YYYYMMDD_HHMMSS
  m = name.match(/(\d{4})(\d{2})(\d{2})[_-](\d{2})(\d{2})(\d{2})/);
  if (m)
    return {
      date: `${m[1]}-${m[2]}-${m[3]}`,
      time: `${m[4]}:${m[5]}:${m[6]}`,
    };
  return { date: null, time: null };
};

const photos = [];
const videos = [];

for (const f of files) {
  const ext = path.extname(f).toLowerCase();
  const entry = { src: `phtotos/${f}`, ...parse(f) };
  if (vids.has(ext)) videos.push(entry);
  else photos.push(entry);
}

// sort oldest first; undated at end
const sorter = (a, b) => {
  if (!a.date && !b.date) return a.src.localeCompare(b.src);
  if (!a.date) return 1;
  if (!b.date) return -1;
  if (a.date !== b.date) return a.date.localeCompare(b.date);
  return (a.time || "").localeCompare(b.time || "");
};
photos.sort(sorter);
videos.sort(sorter);

const out = `// AUTO-GENERATED by make-manifest.js — do not edit by hand.
const MEDIA = {
  photos: ${JSON.stringify(photos, null, 2)},
  videos: ${JSON.stringify(videos, null, 2)},
};
`;
fs.writeFileSync(path.join(__dirname, "media.js"), out, "utf8");
console.log(
  `media.js written: ${photos.length} photos, ${videos.length} videos`
);
